local GLYPH_W, GLYPH_H = 5, 7
local SPACE_W = 3

-- Order matters: the atlas is laid out left to right in exactly this order.
local ORDER = "ABCDEFGHIJKLMNOPQRSTUVWXYZ" ..
              "abcdefghijklmnopqrstuvwxyz" ..
              "0123456789" ..
              ".,!?'\"-_:;*/()+%<>=[]@ "

local function glyphFor(char)
  if G[char] then return G[char] end
  -- Lower case reuses the upper case shapes; the game reads as all-caps.
  local upper = string.upper(char)
  return G[upper]
end

local function widthOf(char)
  if char == " " then return SPACE_W end
  return GLYPH_W
end

--- Build the atlas and return a LOVE Font plus the ImageData it came from.
function Font.build()
  local chars = {}
  for i = 1, #ORDER do chars[#chars + 1] = ORDER:sub(i, i) end

  local totalWidth = 1
  for _, char in ipairs(chars) do
    totalWidth = totalWidth + widthOf(char) + 1
  end

  local data = love.image.newImageData(totalWidth, GLYPH_H + 1)

  -- The top-left pixel defines the separator colour; LOVE splits glyphs on it.
  local sepR, sepG, sepB = 1, 0, 1

  local x = 0
  data:setPixel(x, 0, sepR, sepG, sepB, 1)
  x = x + 1

  for _, char in ipairs(chars) do
    local w = widthOf(char)
    local rows = glyphFor(char)
    if rows then
      for row = 1, GLYPH_H do
        local line = rows[row]
        for col = 1, math.min(w, #line) do
          if line:sub(col, col) == "#" then
            data:setPixel(x + col - 1, row, 1, 1, 1, 1)
          end
        end
      end
    end
    x = x + w
    data:setPixel(x, 0, sepR, sepG, sepB, 1)
    x = x + 1
  end

  local font = love.graphics.newImageFont(data, ORDER, 1)
  font:setFilter("nearest", "nearest")
  return font, data
end

Font.height = GLYPH_H + 1
Font.lineHeight = GLYPH_H + 3

return Font
